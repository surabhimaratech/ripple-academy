function a(
  id: string,
  label: string,
  point: { x: number; y: number },
  pose: Activity["pose"],
  state: Activity["state"],
  weight: number,
  object?: Activity["object"],
): Activity {
  return {
    id,
    label,
    point,
    pose,
    state,
    weight,
    object,
    facing: "up",
    seconds: [30, 60],
    thoughts: [],
  };
}
function seat(
  id: string,
  label: string,
  pose: Activity["pose"],
  state: Activity["state"],
  which: "desk" | "armchair",
  weight: number,
  object?: Activity["object"],
): Activity {
  return {
    ...a(
      id,
      label,
      observatoryFurniture[which].approach,
      pose,
      state,
      weight,
      object,
    ),
    furniture: observatoryFurniture[which].id,
    facing: observatoryFurniture[which].facing,
  };
}
